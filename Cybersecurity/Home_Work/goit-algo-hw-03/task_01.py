"""
Перше завдання

Створіть функцію get_days_from_today(date), яка розраховує кількість днів між заданою датою і поточною датою.

Вимоги до завдання:
1. Функція приймає один параметр: date — рядок, що представляє дату у форматі 'РРРР-ММ-ДД' (наприклад, '2020-10-09').
2. Функція повертає ціле число, яке вказує на кількість днів від заданої дати до поточної. 3. Якщо задана дата пізніша за поточну, результат має бути від'ємним.
4. У розрахунках необхідно враховувати лише дні, ігноруючи час (години, хвилини, секунди).
5. Для роботи з датами слід використовувати модуль datetime Python.

Рекомендації для виконання:
1. Імпортуйте модуль datetime.
2. Перетворіть рядок дати у форматі 'РРРР-ММ-ДД' у об'єкт datetime.
3. Отримайте поточну дату, використовуючи datetime.today().
4. Розрахуйте різницю між поточною датою та заданою датою.
5. Поверніть різницю у днях як ціле число.

Критерії оцінювання:
1. Коректність роботи функції: функція повинна точно обраховувати кількість днів між датами.
2. Обробка винятків: функція має впоратися з неправильним форматом вхідних даних.
3. Читабельність коду: код повинен бути чистим і добре документованим.

Приклад:
Якщо сьогодні 5 травня 2021 року, виклик get_days_from_today("2021-10-09") повинен повернути 157, оскільки 9 жовтня 2021 року є на 157 днів пізніше від 5 травня 2021 року.
"""

from datetime import datetime


def get_days_from_today(date: str) -> int:
    """
    Ця функція розраховує кількість днів від заданої дати до поточної.
    """
    try:
        # 1. Перетворимо рядок у об'єкт datetime
        # Використаємо .date(), щоб відсікти час (години, хвилини) і отримати чисту дату
        target_date = datetime.strptime(date, '%Y-%m-%d').date()
        
        # 2. Отримаємо поточну дату (також відсікаємо час через .date())
        today_date = datetime.today().date()
        
        # 3. Розрахуємо різницю між датами
        # Логіка: Сьогодні - Задана дата
        delta = today_date - target_date
        
        # 4. Повернемо саме кількість днів (.days)
        return delta.days
        
    except ValueError:
        # Якщо формат дати неправильний (наприклад, "2024/12/31" або "hello")
        print(f"Помилка: Неправильний формат дати '{date}'. Використовуйте 'YYYY-MM-DD'.")
        return None


# --- Блок перевірки ---
if __name__ == "__main__":
    # Тест 1: Дата в минулому
    print(f"Днів від 2020-10-09: {get_days_from_today('2020-10-09')}")
    
    # Тест 2: Дата в майбутньому (має бути від'ємне число)
    print(f"Днів до 2027-12-31: {get_days_from_today('2027-12-31')}")
    
    # Тест 3: Сьогодні (має бути 0)
    today_str = datetime.today().strftime('%Y-%m-%d')
    print(f"Днів від сьогодні ({today_str}): {get_days_from_today(today_str)}")
    
    # Тест 4: Помилка
    get_days_from_today("неправильна дата")
