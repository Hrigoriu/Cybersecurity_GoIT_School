import re
from typing import Callable, Generator

def generator_numbers(text: str) -> Generator[float, None, None]:
    """
    Ця функціяе генерує дійсні числа з тексту.    
    :param text: Вхідний рядок тексту.
    :yield: Знайдене число типу float.
    """
    # \b          - межа слова (забезпечує виділення чисел серед тексту)
    # \d+         - одна або більше цифр (ціла частина)
    # (?:\.\d+)?  - необов'язкова група: крапка та дробова частина.
    #               (?:...) означає, що група не створює окремого "capture group".
    pattern = r'\b\d+(?:\.\d+)?\b'
    
    for match in re.finditer(pattern, text):
        yield float(match.group())


def sum_profit(text: str, func: Callable[[str], Generator[float, None, None]]) -> float:
    """
    Ця функція обчислює загальну суму чисел у тексті, використовуючи переданий генератор.    
    :param text: Текст для аналізу.
    :param func: Функція-генератор, що витягує числа з тексту.
    :return: Загальна сума (float).
    """
    # sum() автоматично використовує генератор, додаючи числа по мірі їх надходження
    return sum(func(text))


