def is_palindrome(s: str) -> bool:
    new_s = ""
    
    for char in s:
        if char.isalnum():
            new_s += char.lower()
    
    s = new_s
    length = len(s)
    for i in range(length // 2):
        if s[i] != s[length - i - 1]:
            return False
            
    return True


# Оптимізований варіант (Pythonic way)
def is_palindrome_optimized(s: str) -> bool:
    # Очищуємо рядок (генератор списку) і склеюємо
    cleaned = "".join(char.lower() for char in s if char.isalnum())
    # Порівнюємо рядок з його перевернутою копією (s[::-1])
    return cleaned == cleaned[::-1]


