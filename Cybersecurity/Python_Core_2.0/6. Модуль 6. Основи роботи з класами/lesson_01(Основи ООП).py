"""
    ! Клас !
Це шаблон, з якого створюються об'єкти (у контексті ООП).
Клас це шаблон, а об'єкт це екземпляр класу.
"""
#================================================================================================
class User:
    name = 'Anonymous'
    age = 15

user1 = User()
print(user1.name)
print(user1.age)

