class Pokemon:
    def __init__(self, name, type, health):
        self.name = name        # атрибути класу
        self.type = type        # атрибути класу
        self.health = health    # атрибути класу

    def attack(self, other_pokemon):    # метод класу
        print(f"{self.name} attacks {other_pokemon.name}!")

    def dodge(self):                    # метод класу
        print(f"{self.name} dodged the attack!")

    def evolve(self, new_form):         # метод класу
        print(f"{self.name} is evolving into {new_form}!")
        self.name = new_form

# Створення об'єкта Pikachu / об'єкт класу Pokemon - pikachu
pikachu = Pokemon("Pikachu", "Electric", 100)

# Використання методів
pikachu.attack(Pokemon("Charmander", "Fire", 100))
pikachu.dodge()
pikachu.evolve("Raichu")
"""
Pikachu attacks Charmander!
Pikachu dodged the attack!
Pikachu is evolving into Raichu!
"""
