#================================================================================================
"""
Метод __init__ використовується як конструктор для ініціалізації нових об'єктів класу.
        self використовується для доступу до атрибутів і методів конкретного екземпляра класу.
        Методи можуть звертатися до атрибутів екземпляра через self.
"""
#================================================================================================
class MyClass:
    def __init__(self, value):
        self.instance_field = value  # Поле класу

obj1 = MyClass(5)
obj2 = MyClass(10)

print(obj1.instance_field)  # Виведе: 5
print(obj2.instance_field)  # Виведе: 10
#================================================================================================
"""
    ! Метод класу !
Це функція, яка оперує з полями класу та/або аргументами, які передаються у метод.
"""
#================================================================================================
class Person:
    def __init__(self, name: str, age: int):
        self.name = name
        self.age = age

    def say_name(self) -> None:
        print(f'Hi! I am {self.name} and I am {self.age} years old.')

    def set_age(self, age: int) -> None:
        self.age = age

bob = Person('Boris', 34)

bob.say_name()
bob.set_age(25)
bob.say_name()

