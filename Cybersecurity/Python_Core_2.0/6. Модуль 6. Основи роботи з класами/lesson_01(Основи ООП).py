#================================================================================================
"""
    ! Поле класу ("атрибут екземпляра") !
Це змінна, яка визначена на рівні окремого екземпляра класу. 
Кожен екземпляр класу має свій власний набір полів, які можуть приймати різні значення для різних екземплярів. Полем може бути будь-який об'єкт Python. 
Зазвичай це змінна, або контейнер (словник, список, рядок тощо). 
Поля класу використовуються для зберігання даних, що специфічні для кожного окремого об'єкта.

    ! Змінна об'єкту або поле класу ! 
Це змінна, яка зберігається в об'єкті. 
Вона належать кожному окремому екземпляру класу. 
У цьому випадку кожен об'єкт має свою власну копію поля, тобто вона жодним чином не пов'язана з іншими такими ж полями в інших екземплярах.
"""
#================================================================================================
"""
Атрибути класу спільні для всіх екземплярів, а поля унікальні для кожного екземпляра.
"""
#================================================================================================
class Person:
    count = 0   # атрибут класу/змінна класу - тут count належить класу Person
                # Його значення завжди одне й те саме для любого об'єкту класу.
    def __init__(self, name: str):
        self.name = name    # поле класу/змінна об'єкту - тут змінна name належить об'єкту 
                            # Його значення для кожного об'єкту своє. 
        Person.count += 1

    def how_many_persons(self):
        print(f"Кількість людей зараз {Person.count}")

first = Person('Boris')
first.how_many_persons()
second = Person('Alex')
first.how_many_persons()

