"""
        ! Генератор !
* Це спрощений спосіб створення ітераторів. 
Функція стає генератором, коли містить вираз yield. 
Генератор автоматично реалізує методи __iter__() та __next__().
* Генератори в Python є спрощеним способом створення ітераторів. 
Вони автоматично реалізують методи __iter__() та __next__() за допомогою ключового слова yield.

* Це функція, яка дозволяє декларативно створювати ітератор за допомогою ключового слова yield. 
Він автоматично реалізує методи __iter__() та __next__(), тому більше не потрібно їх явно визначати. Створення генератора - це просто написання функції, яка використовує yield для повернення наступного значення.
"""
#==============================================================================================
def count_down(start):
    current = start
    current -= 1
    while current >= 0:
        yield current
        current -= 1

# Використання генератора
for count in count_down(5):
    print(count)
"""
5
4
3
2
1
0
"""
