"""
Типи NoSQL баз даних:
- Key-Value:
    зберігають дані у вигляді пар ключ-значення, де ключ є унікальним і використовується для доступу до відповідного значення.
    Приклад: Memcached, Redis, Riak.
- Document-Oriented:
    зберігають дані у вигляді документів, які можуть мати складну структуру і підтримують різні типи даних.
    Приклад: MongoDB, CouchDB.
- Object Db:
    зберігають дані у вигляді об'єктів, які можуть мати складну структуру і підтримують різні типи даних.
    Приклад: Realm, db4o, ObjectDB.
- Wide Column Store:
    зберігають дані у вигляді таблиць з рядками і стовпцями, де кожен рядок може мати різну кількість стовпців.
    Приклад: Amazon DynamoDB, Apache Accumulo, Apache Cassandra, HBase.
- Column-Family:
    використовують таблицю з рядками і стовпцями, де кожен рядок може мати різну кількість стовпців.
    Приклад: Apache Cassandra, HBase.
- Graph:
    зберігають дані у вигляді графів, де вузли представляють об'єкти, а ребра представляють зв'язки між ними.
    Приклад: Neo4j, Amazon Neptune.
"""
