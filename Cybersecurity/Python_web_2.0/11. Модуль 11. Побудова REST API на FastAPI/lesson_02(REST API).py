# =======================================================================================================================
"""
    Клієнт-сервер
Перше обмеження вказує, що мережа повинна складатися з клієнтів і серверів.
Сервер — це комп'ютер, у якого є ресурси, що цікавлять,
а клієнт — це комп'ютер, який хоче взаємодіяти з ресурсами, що зберігаються на сервері.

    Stateless
Відсутність стану. Відсутність стану не означає, що сервери та клієнти не мають стану,
це просто означає, що їм не потрібно відслідковувати стан один одного.

    Єдиний інтерфейс
Це обмеження гарантує, що існує спільна мова між серверами та клієнтами,
яка дозволяє замінювати або змінювати кожну частину без порушення роботи всієї системи.
Це досягається за рахунок 4 додаткових обмежень:
-ідентифікація ресурсів
-маніпулювання ресурсами за допомогою представлень
-інформативні (самоописові) повідомлення
-гіпермедіа.

    Кешування
Кешування належить до обмеження,
за якого відповіді сервера повинні бути позначені як кешовані або некешовані.

    Багатошарова (багаторівнева) система
Багатошарова (багаторівнева) система полягає в тому,
що компонентів може бути більше, ніж просто серверів та клієнтів.
Це означає, що у системі може бути більше одного рівня.

    Код за запитом
Необов'язкове обмеження, яке належить до можливості сервера відправляти виконуваний код клієнту.
"""
# =======================================================================================================================
"""
    Основні методи HTTP

    Ідемпотентність
Властивість об'єкта або операції при повторному застосуванні операції до об'єкта
давати той самий результат, як і за першого.
    Безпечність
Операція, яка не змінює стан ресурсу, вважається безпечною.
Безпечні операції можуть бути ідемпотентними,
але не всі ідемпотентні операції є безпечними.
    Ідемпотентність і безпечність
Безпечні операції завжди ідемпотентні, оскільки вони не змінюють стан ресурсу.
Ідемпотентні операції можуть бути безпечними або небезпечними, залежно від того, чи змінюють вони стан ресурсу.

При побудові API, зазвичай, використовуються конкретні методи HTTP для виконання певної дії.
POST: для створення даних.
GET: для читання даних.
PUT: для оновлення даних.
PATCH: для часткового оновлення даних.
DELETE: для видалення даних.
"""
# =======================================================================================================================
"""
    HTTP метод GET
Використовується для отримання (або читання) представлення ресурсу.
У разі успішної адреси, метод GET повертає представлення ресурсу
у форматі XML або JSON в поєднанні з кодом стану HTTP 200 (OK).
У разі невдачі повертається код 404 (NOT FOUND) або 400 (BAD REQUEST).

    HTTP метод POST
Запит найчастіше використовується для створення нових ресурсів.
На практиці він також використовується для створення вкладених ресурсів.
При створенні нового ресурсу POST запит надсилає представлення,
а сервіс бере на себе відповідальність за призначення новому ресурсу ID тощо.
У разі успішного створення ресурсу повертається HTTP код 201 Create,
а також може бути встановлений заголовок Location з адресою створеного ресурсу.

    HTTP метод PUT (PATCH)
Зазвичай використовується для оновлення ресурсу.
Тіло запиту при відправленні PUT-запиту до існуючого ресурсу URL
повинна містити оновлені дані оригінального ресурсу
(повністю, або тільки частину, що оновлюється, — PATCH).
У разі успішного оновлення повертається код 200
(або 204, якщо не було передано будь-який контент у тілі відповіді).

    HTTP метод DELETE
Використовується для видалення ресурсу, ідентифікованого конкретним URL (ID).
У разі успішного видалення ресурсу повертається
код 200 (OK) HTTP спільно з тілом відповіді, що містить дані видаленого ресурсу.
Також можливе використання HTTP коду 204 (NO CONTENT) без тіла відповіді.
"""
