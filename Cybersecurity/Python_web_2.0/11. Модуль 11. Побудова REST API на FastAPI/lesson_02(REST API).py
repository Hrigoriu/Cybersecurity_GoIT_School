"""
        ! REST API !

Це архітектурний стиль для створення веб-сервісів,
який використовує HTTP-протокол для обміну даними між клієнтом і сервером.

REST API базується на принципах REST (Representational State Transfer),
які визначають, як ресурси (дані) повинні бути представлені
і як клієнт може взаємодіяти з ними через HTTP-методи (GET, POST, PUT, DELETE).

REST API дозволяє створювати гнучкі, масштабовані і легко підтримувані веб-сервіси,
які можуть бути використані різними клієнтами, такими як веб-браузери, мобільні додатки або інші сервери.
"""
# =======================================================================================================================
"""
REST (REpresentational State Transfer) розшифровується як передача репрезентативного стану.
Це набір принципів проектування для підвищення масштабованості і гнучкості мережевих комунікацій.
"""
# =======================================================================================================================
"""
URI - це ідентифікатор конкретного ресурсу. Як сторінка, книга або документ.

URL - Це особливий тип ідентифікатора, який також говорить вам, як отримати доступ до нього.

Існує наступна традиційна форма запису `URL:
<scheme>://[<login>[:<password>]@]<host>[:<port>]][/<path>][?<query>][#<fragment>]

Приклад:
https://user:password@host.com:80/resourse/path/?query=name&ttt=123#hash

У цьому записі:
- scheme — Це мережевий протокол, за яким відбувається звернення до ресурсу
- login — не обов'язковий параметр, ім'я користувача, яке використовується для доступу до ресурсу
- password — пароль вказаного користувача, якщо він необхідний
- host — повністю прописане доменне ім'я хоста в системі
    DNS (goit.ua) або IP-адреса хоста у формі чотирьох груп десяткових чисел, розділених крапками
- port — порт хоста для підключення.
    Згадайте, ми використовували http://localhost:3000, де 3000 — це і є порт.
    Виникає закономірне питання: чому порт не вказується, наприклад, для URL у браузері.
    Просто браузер знає, що для протоколу http порт дорівнює 80,
    а для https він дорівнює 443 і підставляє його за нас
- path — уточнююча інформація про місце знаходження ресурсу.
- query — рядок запиту з параметрами, що передаються на сервер (методом GET).
    Починається із символу ?, роздільник параметрів — знак &. Приклад: ?foo=123&baz=234&bar=value
- fragment — ідентифікатор із попереднім символом #.
    Часто його називають хеш — hash або якір.
    Якорем може бути вказаний заголовок всередині документа або атрибут id елемента.
    За таким посиланням браузер відкриє сторінку та перемістить вікно перегляду до зазначеного елемента.
    Наприклад, посилання на секцію контактів у лендінгу: https://example.com/#contact.
"""
