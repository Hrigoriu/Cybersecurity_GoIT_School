"""
Формування URL для REST API

При формуванні URL для REST API важливо дотримуватися певних правил і рекомендацій,
щоб забезпечити зрозумілість, логічність і зручність використання API.
Ось деякі основні принципи формування URL для REST API:
1. Використовуйте іменники для ресурсів:
   URL повинні містити іменники, які описують ресурси, до яких вони відносяться.
   Наприклад, /users для колекції користувачів або /products для колекції продуктів.
2. Використовуйте множину для колекцій:
   Якщо URL представляє колекцію ресурсів, використовуйте множину для імені ресурсу.
   Наприклад, /users для колекції користувачів, а не /user.
3. Використовуйте ієрархію для відображення відносин між ресурсами:
   Якщо ресурси мають ієрархічні відносини, використовуйте ієрархію в URL для відображення цих відносин.
   Наприклад, /users/{userId}/orders для замовлень конкретного користувача.
4. Використовуйте параметри запиту для фільтрації, сортування і пагінації:
   Для фільтрації, сортування і пагінації ресурсів використовуйте параметри запиту в URL.
   Наприклад, /products?category=electronics для фільтрації продуктів за категорією або /users?sort=asc для сортування користувачів за зростанням.
5. Уникайте використання дієслів у URL:
   URL повинні містити іменники, а не дієслова. Це допомагає зробити URL більш зрозумілими і логічними.
    Наприклад, використовуйте /users для колекції користувачів, а не /getUsers або /createUser.
6. Використовуйте нижнє підкреслення або дефіс для розділення слів:
   Для покращення читабельності URL використовуйте нижнє підкреслення (_) або дефіс (-) для розділення слів.
   Наприклад, /user_profiles або /user-profiles для колекції профілів користувачів.
7. Використовуйте версіонування API:
    Якщо ви плануєте вносити зміни в API, які можуть порушити сумісність з попередніми версіями,
    використовуйте версіонування в URL.
    Наприклад, /v1/users для першої версії API і /v2/users для другої версії API.
Дотримання цих принципів допоможе створити зрозумілий, логічний і зручний для використання REST API, який буде легко підтримувати і розширювати в майбутньому.
"""
