"""
Часто кінцеві URL за запитом ресурсу називають endpoints API.
Endpoint — це конкретна URL-адреса, яка відповідає певному ресурсу або дії в API.
Наприклад, якщо у вас є API для управління користувачами, то кінцеві URL можуть бути такими:
- GET /users — отримати список всіх користувачів
- POST /users — створити нового користувача
- GET /users/{id} — отримати інформацію про конкретного користувача за його ID
- PUT /users/{id} — оновити інформацію про конкретного користувача за його ID
- DELETE /users/{id} — видалити користувача за його ID
Endpoints API є важливою частиною дизайну API, оскільки вони визначають,
як клієнти можуть взаємодіяти з ресурсами і виконувати різні дії в системі.
"""
# =======================================================================================================================
"""
Пагінація здійснюється через query рядок за допомогою параметра offset —
це початковий номер позиції і параметра limit — максимальна кількість елементів, що повертаються.
Вони можуть називатися і по-іншому, наприклад skip, limit.address, page, size і т.д.
Наприклад, якщо у вас є API для отримання списку користувачів, то ви можете використовувати пагінацію,
щоб обмежити кількість користувачів, які повертаються в одному запиті.
Наприклад, якщо ви хочете отримати перші 10 користувачів,ви можете зробити запит GET /users?offset=0&limit=10.
Якщо ви хочете отримати наступні 10 користувачів, ви можете зробити запит GET /users?offset=10&limit=10, і так далі.
Пагінація допомагає зменшити навантаження на сервер і покращити продуктивність,
особливо коли у вас є велика кількість даних, які потрібно повернути клієнту.
"""
# =======================================================================================================================
"""
Складна фільтрація за значеннями.
Можна використовувати роздільник — подвійна двокрапка ::,
яка відокремлює ім'я властивості від значення порівняння.
Наприклад, якщо ви хочете отримати всіх користувачів, які старші за 18 років,
ви можете зробити запит GET /users?age::gt=18.
У цьому прикладі age — це ім'я властивості, gt — це оператор порівняння (greater than),
а 18 — це значення, з яким порівнюється властивість.
Існують різні оператори порівняння, які можна використовувати для складної фільтрації,
такі як eq (equal), ne (not equal), lt (less than), lte (less than or equal),
gt (greater than), gte (greater than or equal) і т.д.
Цей підхід дозволяє створювати більш гнучкі і потужні API,
які можуть обробляти складні запити і фільтрацію даних на сервері,
що зменшує навантаження на клієнта і покращує продуктивність.
"""
# =======================================================================================================================
"""
Сортування. Один із способів, коли для кожної властивості, що передається,
здійснюється сортування в порядку зростання, а для кожної властивості з префіксним тире ("-") -
сортування здійснюється в порядку спадання.
Сепаратор для кожного імені властивості — вертикальна смуга ("|").
Наприклад, якщо ви хочете отримати список користувачів, відсортованих за віком у порядку зростання,
а потім за ім'ям у порядку спадання, ви можете зробити запит GET /users?sort=age|-name.
У цьому прикладі age — це ім'я властивості, за якою відбувається сортування в порядку зростання,
а -name — це ім'я властивості, за якою відбувається сортування в порядку спадання.
Цей підхід дозволяє створювати більш гнучкі і потужні API,
які можуть обробляти складні запити і сортування даних на сервері,
що зменшує навантаження на клієнта і покращує продуктивність
"""
# =======================================================================================================================
