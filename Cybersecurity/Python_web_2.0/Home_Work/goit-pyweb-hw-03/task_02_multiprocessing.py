# multiprocessing - це використання всіх ядер процесора в Python
# Pool - створює групу процесів-робітників
# cpu_count - дізнається, скільки ядер має ваш процесор
from multiprocessing import Pool, cpu_count, current_process  # Імпортуємо бібліотеку для multiprocessing

# Налаштуємо логування: просте виведення повідомлень в консоль
logging.basicConfig(level=logging.INFO, format='%(message)s')

def find_divisors(num: int) -> list[int]:
    """
    Створимо функцію-робітника. Вона знаходить усі дільники для одного числа.
    
    Це CPU-bound задача: вона вимагає багато математичних обчислень.
    Чим більше число, тим довше вона працює. 
    Саме такі задачі ідеально підходять для паралельної обробки (multiprocessing).
    """
    divisors = []
    # Проходимо цикл від 1 до самого числа
    # (алгоритм O(N) спеціально обраний для створення навантаження)
    for i in range(1, num + 1):
        if num % i == 0:  # Якщо ділиться без залишку
            divisors.append(i)
    return divisors

def factorize_sync(*numbers):
    """
    Створимо функцію ,яка показує синхронну (послідовну) версію.
    
    Як це працює:
    Бере перше число -> рахує -> закінчує.
    Бере друге число -> рахує -> закінчує.
    І так далі. Працює тільки одне ядро процесора.
    """
    results = []
    for num in numbers:
        # Викликаємо функцію просто як зазвичай
        results.append(find_divisors(num))
    return results

def factorize_parallel(*numbers):
    """
    Створимо функцію ,яка показує паралельну версію.
    
    Як це працює:
    Створює кілька незалежних процесів (копій програми).
    Роздає їм числа. Всі процеси рахують одночасно на різних ядрах.
    """
    # 1. Дізнаємось потужність комп'ютера (наприклад, 4, 8 або 16 ядер)
    cores = cpu_count()
    
    # 2. Створимо пул (групу) процесів.
    # with гарантує, що процеси будуть коректно закриті після роботи.
    with Pool(processes=cores) as pool:
        # 3. pool.map - це основа всього.
        # Вона бере функцію (find_divisors) і список даних (numbers).
        # Вона автоматично розбиває список і роздає задачі вільним процесам.
        # Результат збирається в список results у тому ж порядку, що й вхідні дані.
        results = pool.map(find_divisors, numbers)
        
    return results

