import sqlite3


def create_db():
    """
    Створимо функцію для читання SQL-файлу та створення структури бази даних.
    """
    # 1. Відкриваємо файл university.sql для читання ('r').
    # Використовуємо encoding="utf-8" для уникнення проблем з кирилицею.
    with open("university.sql", "r", encoding="utf-8") as f:
        sql = f.read()  # Зберігаємо весь текст SQL-скрипта у змінну sql

    # 2. Встановлюємо з'єднання з БД.
    # Якщо файлу university.db не існує, SQLite автоматично його створить.
    with sqlite3.connect("university.db") as con:
        cur = con.cursor()  # Курсор - це об'єкт для взаємодії з БД

        # 3. executescript() використовується замість execute(), коли
        # потрібно виконати відразу багато SQL-команд (розділених ';').
        cur.executescript(sql)

    # Виводимо повідомлення про успішне завершення
    print("Базу даних та таблиці успішно створено!")


# Точка входу: код нижче виконається лише якщо цей файл запущено напряму
if __name__ == "__main__":
    create_db()
