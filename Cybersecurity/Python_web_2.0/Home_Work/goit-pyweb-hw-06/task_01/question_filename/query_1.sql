-- Завдання: Знайти 5 студентів із найбільшим середнім балом з усіх предметів.

-- Вибираємо ім'я студента та рахуємо середнє значення оцінки (AVG), 
-- округляючи його до 2 знаків після коми (ROUND). Називаємо цю колонку avg_grade.
SELECT s.fullname, ROUND(AVG(g.grade), 2) AS avg_grade
FROM students s
-- Приєднуємо таблицю оцінок, де ID студента збігається.
JOIN grades g ON s.id = g.student_id
-- Групуємо результати за ID студента, щоб середній бал розраховувався для кожної людини окремо.
GROUP BY s.id
-- Сортуємо результати за середнім балом у порядку спадання (DESC).
ORDER BY avg_grade DESC
-- Залишаємо лише перші 5 рядків (найкращих студентів).
LIMIT 5;