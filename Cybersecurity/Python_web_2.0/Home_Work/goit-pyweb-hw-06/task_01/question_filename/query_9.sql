-- Завдання: Знайти список курсів, які відвідує студент (наприклад, студент=1).

-- DISTINCT гарантує, що якщо студент має 5 оцінок з Математики, 
-- слово "Математика" виведеться лише 1 раз, а не 5.
SELECT DISTINCT sub.name
FROM subjects sub
-- Приєднуємо оцінки, щоб дізнатися, з яких предметів студент має записи
JOIN grades g ON sub.id = g.subject_id
WHERE g.student_id = 1;